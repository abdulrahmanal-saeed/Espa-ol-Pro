"""Generates the Español Pro Android icon and splash resources.

The mark is the letter «ñ» from the bundled Inter Bold font (SIL OFL 1.1)
in white on the brand teal. Everything except the legacy PNG fallbacks is a
vector drawable, so it is sharp at every screen density.

Usage (needs fonttools and pillow):

    python tool/brand/generate_android_icons.py

Writes into android/app/src/main/res/. Re-run after changing the colours or
the glyph; the output is deterministic.
"""

from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
FONT = ROOT / "assets/fonts/Inter-700.ttf"
RES = ROOT / "android/app/src/main/res"
GLYPH = "ñ"

BRAND = "#0E5E6F"        # deep teal, same seed as the Flutter theme
BRAND_NIGHT = "#08343D"  # darker teal for dark-mode splash
MARK = "#FFFFFF"

# Adaptive icons are drawn on a 108×108 dp canvas; launchers may crop to the
# central 66 dp circle. The glyph is kept inside a 50 dp box for margin.
CANVAS = 108.0
BOX = 50.0


def glyph_path():
    font = TTFont(FONT)
    gs = font.getGlyphSet()
    name = font.getBestCmap()[ord(GLYPH)]
    bounds = BoundsPen(gs)
    gs[name].draw(bounds)
    x0, y0, x1, y1 = bounds.bounds
    w, h = x1 - x0, y1 - y0
    scale = BOX / max(w, h)
    # Font units are y-up; Android vectors are y-down. Centre on the canvas.
    dx = (CANVAS - w * scale) / 2 - x0 * scale
    dy = (CANVAS + h * scale) / 2 + y0 * scale
    svg = SVGPathPen(gs, ntos=lambda v: f"{v:.3f}".rstrip("0").rstrip("."))
    gs[name].draw(TransformPen(svg, (scale, 0, 0, -scale, dx, dy)))
    return svg.getCommands()


def vector(path, color, size_dp=108):
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand/generate_android_icons.py — do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size_dp}dp"
    android:height="{size_dp}dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="{color}"
        android:pathData="{path}" />
</vector>
"""


def write(rel, text):
    p = RES / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8")
    print("wrote", p.relative_to(ROOT))


def legacy_png(px):
    """Pre-Android-8 launchers: rounded square, supersampled for clean edges."""
    ss = 8
    size = px * ss
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    pad = round(size * 0.04)
    d.rounded_rectangle(
        [pad, pad, size - pad, size - pad], radius=round(size * 0.22), fill=BRAND
    )
    font = ImageFont.truetype(str(FONT), round(size * 0.62))
    l, t, r, b = d.textbbox((0, 0), GLYPH, font=font)
    d.text(((size - (r - l)) / 2 - l, (size - (b - t)) / 2 - t), GLYPH,
           font=font, fill=MARK)
    return img.resize((px, px), Image.LANCZOS)


def main():
    path = glyph_path()
    write("drawable/ic_launcher_foreground.xml", vector(path, MARK))
    # Android 13 themed icons tint this layer; the colour is ignored.
    write("drawable/ic_launcher_monochrome.xml", vector(path, "#FF000000"))
    write("mipmap-anydpi-v26/ic_launcher.xml", """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand/generate_android_icons.py — do not edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/brand_teal" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
""")
    write("values/colors.xml", f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand/generate_android_icons.py — do not edit. -->
<resources>
    <color name="brand_teal">{BRAND}</color>
    <color name="splash_background">{BRAND}</color>
</resources>
""")
    write("values-night/colors.xml", f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand/generate_android_icons.py — do not edit. -->
<resources>
    <color name="splash_background">{BRAND_NIGHT}</color>
</resources>
""")
    # Pre-Android-12 splash: brand colour with the mark centred.
    launch = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand/generate_android_icons.py — do not edit. -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@color/splash_background" />
    <item
        android:width="160dp"
        android:height="160dp"
        android:gravity="center"
        android:drawable="@drawable/ic_launcher_foreground" />
</layer-list>
"""
    write("drawable/launch_background.xml", launch)
    write("drawable-v21/launch_background.xml", launch)
    night = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand/generate_android_icons.py — do not edit. -->
<resources>
    <!-- Android 12+ system splash screen. -->
    <style name="LaunchTheme" parent="@android:style/Theme.{base}.NoTitleBar">
        <item name="android:windowSplashScreenBackground">@color/splash_background</item>
        <item name="android:windowSplashScreenAnimatedIcon">@drawable/ic_launcher_foreground</item>
        <item name="android:windowBackground">@drawable/launch_background</item>
    </style>
    <style name="NormalTheme" parent="@android:style/Theme.{base}.NoTitleBar">
        <item name="android:windowBackground">?android:colorBackground</item>
    </style>
</resources>
"""
    write("values-v31/styles.xml", night.format(base="Light"))
    write("values-night-v31/styles.xml", night.format(base="Black"))
    for folder, px in [("mdpi", 48), ("hdpi", 72), ("xhdpi", 96),
                       ("xxhdpi", 144), ("xxxhdpi", 192)]:
        out = RES / f"mipmap-{folder}/ic_launcher.png"
        legacy_png(px).save(out, optimize=True)
        print("wrote", out.relative_to(ROOT))


if __name__ == "__main__":
    main()
